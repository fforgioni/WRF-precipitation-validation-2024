# -*- coding: utf-8 -*-
"""Generate station-based precipitation verification maps.

Author: Fernando Primo Forgioni (ORCID: 0000-0003-3233-8957).
Input: results/Metricas.xlsx, generated by 04_station_metrics.py.
Outputs: five PNG maps in figures/ (correlation, RMSE, bias, POD, FAR).
Run: python scripts/05_station_metrics_maps.py
Natural Earth geographic boundaries may require internet access.
"""

import os
import argparse
from pathlib import Path
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import matplotlib.colors as mcolors
import matplotlib.cm as cm
import matplotlib.ticker as mticker
from matplotlib.patches import Rectangle

import cartopy.crs as ccrs
import cartopy.feature as cfeature
from cartopy.io import shapereader

# =====================================================
# 1. CONFIGURACIÓN
# =====================================================

repository_root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--results-dir", type=Path, default=repository_root / "results")
parser.add_argument("--figures-dir", type=Path, default=repository_root / "figures")
args = parser.parse_args()

archivo = args.results_dir / "Metricas.xlsx"
carpeta_salida = args.figures_dir
if not archivo.is_file():
    raise FileNotFoundError(
        f"Required input file not found: {archivo}. "
        "Run 04_station_metrics.py first."
    )
carpeta_salida.mkdir(parents=True, exist_ok=True)

output_names = {
    "CC": "station_correlation.png",
    "RMSE": "Station_RMSE.png",
    "BIAS": "Station_bias.png",
    "POD": "Station_POD.png",
    "FAR": "Station_FAR.png",
}

# =====================================================
# 2. CONFIGURACIÓN DE LAS MÉTRICAS
# =====================================================

metricas = {

    "CC": {
        "cmap": "RdBu",
        "niveles": np.linspace(-1, 1, 11),
        "ticks": np.linspace(-1, 1, 11),
        "label": "Correlation coefficient",
        "extend": "neither",
        "formato": "%.1f"
    },

    "RMSE": {
        "cmap": "YlOrRd",
        "niveles": np.arange(0, 181, 20),
        "ticks": np.arange(0, 181, 20),
        "label": "RMSE (mm)",
        "extend": "max",
        "formato": "%.0f"
    },

    "BIAS": {
        "cmap": "RdBu_r",
        "niveles": np.arange(-160, 161, 20),
        "ticks": np.arange(-160, 161, 20),
        "label": "Bias (mm)",
        "extend": "both",
        "formato": "%.0f"
    },

    "POD": {
        "cmap": "YlGn",
        "niveles": np.linspace(0, 1, 6),
        "ticks": np.linspace(0, 1, 6),
        "label": "Probability of detection",
        "extend": "neither",
        "formato": "%.1f"
    },

    "FAR": {
        "cmap": "YlOrRd",
        "niveles": np.linspace(0, 1, 6),
        "ticks": np.linspace(0, 1, 6),
        "label": "False alarm ratio",
        "extend": "neither",
        "formato": "%.1f"
    }
}

# =====================================================
# 3. SIMULACIONES Y PRODUCTOS
# =====================================================

simulaciones = [
    "GF-ERA5",
    "GF-GFS",
    "KF-ERA5",
    "KF-GFS",
    "PERSIANN",
    "MERGE"
]

titulos = [
    "(a) Grell-Freitas / ERA5",
    "(b) Grell-Freitas / GFS",
    "(c) Kain-Fritsch / ERA5",
    "(d) Kain-Fritsch / GFS",
    "(e) PERSIANN",
    "(f) MERGE"
]

# =====================================================
# 4. CONFIGURACIÓN GRÁFICA
# =====================================================

plt.rcParams.update({
    "font.family": "DejaVu Sans",
    "font.size": 11,
    "axes.linewidth": 0.8
})

proyeccion = ccrs.PlateCarree()

extent = [-58.5, -48.5, -34.5, -26.5]

# -------- ZOOM --------
# Ajustá esta caja si querés mover o agrandar la región ampliada
zoom_extent = [-51.5, -50.9, -30.25, -29.75]
# [lon_min, lon_max, lat_min, lat_max]

# Tamaños de fuente
fontsize_titulos = 13
fontsize_ticks = 14
fontsize_colorbar = 16

# Tamaño de puntos
tam_punto_main = 45
tam_punto_zoom = 12

# =====================================================
# 5. LÍMITES GEOGRÁFICOS
# =====================================================

estados = cfeature.NaturalEarthFeature(
    category="cultural",
    name="admin_1_states_provinces_lines",
    scale="10m",
    facecolor="none"
)

shp = shapereader.natural_earth(
    resolution="10m",
    category="cultural",
    name="admin_1_states_provinces"
)

rs = [
    registro.geometry
    for registro in shapereader.Reader(shp).records()
    if registro.attributes.get("name") == "Rio Grande do Sul"
]

if not rs:
    raise ValueError("No se encontró Rio Grande do Sul.")

# =====================================================
# 6. FUNCIÓN PARA CREAR EL MAPA BASE
# =====================================================

def mapa_base(ax):

    ax.set_extent(extent, crs=proyeccion)

    ax.add_feature(
        cfeature.LAND.with_scale("10m"),
        facecolor="#f5f5f5",
        zorder=0
    )

    ax.add_feature(
        cfeature.OCEAN.with_scale("10m"),
        facecolor="#dcecf5",
        zorder=0
    )

    ax.add_feature(
        cfeature.LAKES.with_scale("10m"),
        facecolor="#dcecf5",
        edgecolor="gray",
        linewidth=0.3,
        zorder=2
    )

    ax.add_feature(
        cfeature.COASTLINE.with_scale("10m"),
        linewidth=0.6,
        zorder=3
    )

    ax.add_feature(
        cfeature.BORDERS.with_scale("10m"),
        linewidth=0.6,
        edgecolor="#555555",
        zorder=3
    )

    ax.add_feature(
        estados,
        edgecolor="#999999",
        linewidth=0.4,
        zorder=3
    )

    ax.add_geometries(
        rs,
        crs=proyeccion,
        facecolor="none",
        edgecolor="#333333",
        linewidth=0.9,
        zorder=4
    )

# =====================================================
# 7. FUNCIÓN PARA AGREGAR ZOOM
# =====================================================

def agregar_zoom(ax, df_panel, valores, cmap, norm):

    validos = np.isfinite(valores)

    # ---------------------------------------------
    # Rectángulo de la región ampliada en mapa base
    # ---------------------------------------------

    rect = Rectangle(
        (zoom_extent[0], zoom_extent[2]),
        zoom_extent[1] - zoom_extent[0],
        zoom_extent[3] - zoom_extent[2],
        fill=False,
        edgecolor="black",
        linewidth=1.0,
        linestyle="-",
        transform=proyeccion,
        zorder=10
    )

    ax.add_patch(rect)

    # ---------------------------------------------
    # Inset con zoom
    # ---------------------------------------------

    axins = ax.inset_axes(
        [0.72, 0.03, 0.26, 0.26],
        projection=proyeccion
    )
    axins.set_extent(zoom_extent, crs=proyeccion)

    axins.add_feature(
        cfeature.LAND.with_scale("10m"),
        facecolor="#f5f5f5",
        zorder=0
    )

    axins.add_feature(
        cfeature.OCEAN.with_scale("10m"),
        facecolor="#dcecf5",
        zorder=0
    )

    axins.add_feature(
        cfeature.LAKES.with_scale("10m"),
        facecolor="#dcecf5",
        edgecolor="gray",
        linewidth=0.2,
        zorder=1
    )

    axins.add_feature(
        cfeature.COASTLINE.with_scale("10m"),
        linewidth=0.5,
        zorder=2
    )

    axins.add_feature(
        cfeature.BORDERS.with_scale("10m"),
        linewidth=0.4,
        edgecolor="#555555",
        zorder=2
    )

    axins.add_feature(
        estados,
        edgecolor="#999999",
        linewidth=0.3,
        zorder=2
    )

    axins.add_geometries(
        rs,
        crs=proyeccion,
        facecolor="none",
        edgecolor="#333333",
        linewidth=0.7,
        zorder=3
    )

    # Estaciones válidas
    axins.scatter(
        df_panel.loc[validos, "longitud"],
        df_panel.loc[validos, "latitud"],
        c=valores[validos],
        cmap=cmap,
        norm=norm,
        s=tam_punto_zoom,
        marker="o",
        edgecolor="black",
        linewidth=0.5,
        transform=proyeccion,
        zorder=5
    )

    # Estaciones inválidas
    if (~validos).any():
        axins.scatter(
            df_panel.loc[~validos, "longitud"],
            df_panel.loc[~validos, "latitud"],
            s=tam_punto_zoom,
            marker="o",
            facecolor="#bdbdbd",
            edgecolor="black",
            linewidth=0.5,
            transform=proyeccion,
            zorder=4
        )

    # Sin etiquetas en el inset
    axins.set_xticks([])
    axins.set_yticks([])

    # Borde del inset
    for spine in axins.spines.values():
        spine.set_linewidth(0.9)
        spine.set_edgecolor("black")

# =====================================================
# 8. GENERAR UNA FIGURA POR MÉTRICA
# =====================================================

for metrica, config in metricas.items():

    print(f"Generando mapa de {metrica}...")

    df = pd.read_excel(
        archivo,
        sheet_name=metrica
    )

    df.columns = df.columns.str.strip()

    faltantes = [
        nombre for nombre in simulaciones
        if nombre not in df.columns
    ]

    if faltantes:
        raise ValueError(
            f"En la hoja {metrica} faltan las columnas: {faltantes}"
        )

    df["latitud"] = pd.to_numeric(df["latitud"], errors="coerce")
    df["longitud"] = pd.to_numeric(df["longitud"], errors="coerce")

    df = df.dropna(subset=["latitud", "longitud"])

    fig, axs = plt.subplots(
        3, 2,
        figsize=(13, 15),
        subplot_kw={"projection": proyeccion}
    )

    axs = axs.flatten()

    niveles = config["niveles"]

    cmap = plt.get_cmap(
        config["cmap"],
        len(niveles) - 1
    )

    norm = mcolors.BoundaryNorm(
        niveles,
        cmap.N,
        clip=False
    )

    for i, simulacion in enumerate(simulaciones):

        ax = axs[i]

        mapa_base(ax)

        valores = pd.to_numeric(
            df[simulacion],
            errors="coerce"
        )

        validos = np.isfinite(valores)

        # Mapa principal
        ax.scatter(
            df.loc[validos, "longitud"],
            df.loc[validos, "latitud"],
            c=valores[validos],
            cmap=cmap,
            norm=norm,
            s=tam_punto_main,
            marker="o",
            edgecolor="black",
            linewidth=0.5,
            transform=proyeccion,
            zorder=6
        )

        if (~validos).any():
            ax.scatter(
                df.loc[~validos, "longitud"],
                df.loc[~validos, "latitud"],
                s=tam_punto_main,
                marker="o",
                facecolor="#bdbdbd",
                edgecolor="black",
                linewidth=0.5,
                transform=proyeccion,
                zorder=5
            )

        ax.set_title(
            titulos[i],
            fontsize=fontsize_titulos,
            fontweight="bold",
            loc="center",
            pad=9
        )

        # Agregar zoom
        agregar_zoom(ax, df, valores, cmap, norm)

    fig.subplots_adjust(
        left=0.04,
        right=0.86,
        bottom=0.04,
        top=0.96,
        wspace=0.04,
        hspace=0.12
    )

    sm = cm.ScalarMappable(
        cmap=cmap,
        norm=norm
    )
    sm.set_array([])

    cax = fig.add_axes([
        0.89,
        0.15,
        0.022,
        0.70
    ])

    cbar = fig.colorbar(
        sm,
        cax=cax,
        orientation="vertical",
        boundaries=niveles,
        ticks=config["ticks"],
        spacing="uniform",
        extend=config["extend"],
        format=mticker.FormatStrFormatter(config["formato"])
    )

    cbar.set_label(
        config["label"],
        fontsize=fontsize_colorbar,
        labelpad=15
    )

    cbar.ax.tick_params(
        axis="y",
        which="major",
        labelsize=fontsize_ticks,
        length=4,
        width=0.8,
        pad=5
    )

    cbar.ax.minorticks_off()
    cbar.outline.set_linewidth(0.8)

    salida = os.path.join(
        carpeta_salida,
        output_names[metrica]
    )

    fig.savefig(
        salida,
        dpi=600,
        format="png",
        bbox_inches="tight",
        facecolor="white"
    )

    print(f"Guardado: {salida}")

    plt.show()
    plt.close(fig)

print("\nTodas las figuras fueron generadas.")